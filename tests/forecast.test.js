const assert=require('node:assert/strict');
const fs=require('node:fs');
const F=require('../public/assets/forecast.js');
const data=JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'../public/data/season.json'),'utf8'));
const fixtures=F.remainingFixtures(data);
assert.equal(data.standings.length,11);
assert.equal(fixtures.length,12);
assert.equal(fixtures.filter(f=>f.date).length,3);
assert.deepEqual(fixtures.slice(0,3).map(x=>x.date),['2026-11-14','2026-11-21','2026-11-28']);
assert.equal(F.forecast(data).points,25);
assert.equal(F.forecast(data).position,8);
assert.equal(F.forecast(data,{},'best').points,46);
assert.equal(F.forecast(data,{},'worst').points,10);
const allWins=Object.fromEntries(fixtures.map(f=>[f.id,{homeScore:f.home===data.team?2:0,awayScore:f.away===data.team?2:0}]));
assert.equal(F.forecast(data,allWins).position,1);
assert.equal(F.forecast(data,allWins).points,46);
assert.equal(F.forecast(data,allWins).selected,12);
assert.equal(F.forecast(data,allWins).selectedWins,12);
const first=fixtures[0];
const single={ [first.id]:{homeScore:0,awayScore:2} };
assert.equal(F.forecast(data,single).selected,1);
assert.equal(F.forecast(data,single).selectedWins,1);
assert.equal(F.forecast(data,single,'worst').points,13);
assert(!F.validPick({homeScore:0}));
assert(F.validPick({homeScore:0,awayScore:0}));
console.log('Projection tests passed');
